export const getLang = () => { try { return localStorage.getItem('om-lang') || 'en'; } catch { return 'en'; } };
export const setLang = (l) => { try { localStorage.setItem('om-lang', l); } catch { /* storage blocked */ } };
export function t(key, ...args) {
  const v = STR[getLang()][key] ?? STR.en[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}
export const L = (o) => (o && typeof o === 'object' ? (o[getLang()] ?? o.en) : o ?? '');
export function applyDir() {
  const ar = getLang() === 'ar';
  document.documentElement.lang = ar ? 'ar' : 'en';
  document.documentElement.dir = ar ? 'rtl' : 'ltr';
}
